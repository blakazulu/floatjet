export const allArticles: Article[] = [
  ...blogArticles,
  ...gearArticles,
  ...guidesArticles,
  ...toolsArticles,
];

// =============================================================================
// HELPER FUNCTIONS
// =============================================================================

/**
 * Get an article by its slug (searches all sections)
 */
export function getArticleBySlug(slug: string): Article | undefined {
  return allArticles.find((article) => article.slug === slug);
}

/**
 * Get all articles for a specific section
 */
export function getArticlesBySection(section: Section): Article[] {
  return allArticles.filter((article) => article.section === section);
}

/**
 * Get articles by section and category
 */
export function getArticlesByCategory(section: Section, category: string): Article[] {
  return allArticles.filter(
    (article) => article.section === section && article.category.toLowerCase() === category.toLowerCase()
  );
}

/**
 * Get featured articles for a section
 */
export function getFeaturedArticles(section: Section): Article[] {
  return allArticles.filter((article) => article.section === section && article.featured);
}

/**
 * Get all unique categories for a section
 */
export function getCategoriesForSection(section: Section): string[] {
  const categories = allArticles
    .filter((article) => article.section === section)
    .map((article) => article.category)
    .filter((category) => category !== "");
  return Array.from(new Set(categories));
}

/**
 * Get the URL path for an article
 */
export function getArticlePath(article: Article): string {
  return `/${article.section}/${article.slug}`;
}
